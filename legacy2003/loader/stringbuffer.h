/**
 * StringBuffer class
 *
 * class for handling strings with variable length
 *
 *
 * @author: Andor Greissl
 * @date:   29.03.2003
 *
 */

#ifndef STRINGBUFFER_H
#define STRINGBUFFER_H


class StringBuffer
{
private:
	// buffer with the string
   char *buffer;

	// length of the string
	int   len;

	// maximum length
	int   maxlen;

public:

	/////////////////////////////////////////////////////////////////////////////
	// constructs a standard StringBuffer
	// object with the starting buffer length
	/////////////////////////////////////////////////////////////////////////////
	StringBuffer(int len=1024);


	/////////////////////////////////////////////////////////////////////////////
	// destructor for the stringbuffer
	/////////////////////////////////////////////////////////////////////////////
	~StringBuffer();


	/////////////////////////////////////////////////////////////////////////////
	// appends a character
	/////////////////////////////////////////////////////////////////////////////
	void append(char c);


	/////////////////////////////////////////////////////////////////////////////
	// appends a string
	/////////////////////////////////////////////////////////////////////////////
	void append(char *str);


	/////////////////////////////////////////////////////////////////////////////
	// clears the string
	/////////////////////////////////////////////////////////////////////////////
	void clear();


	/////////////////////////////////////////////////////////////////////////////
	// sets the length of the string
	/////////////////////////////////////////////////////////////////////////////
	void setLength(int len);

	/////////////////////////////////////////////////////////////////////////////
	// returns a char * to the buffer
	/////////////////////////////////////////////////////////////////////////////
	const char * operator*();


	/////////////////////////////////////////////////////////////////////////////
	// remove the last char from the stringbuffer
	/////////////////////////////////////////////////////////////////////////////
	void operator--(int);
};


#endif


