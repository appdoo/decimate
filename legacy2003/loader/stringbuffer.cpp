#include <string.h>
#include "stringbuffer.h"




/////////////////////////////////////////////////////////////////////////////
// constructs a standard StringBuffer
// object with the starting buffer length
/////////////////////////////////////////////////////////////////////////////
StringBuffer::StringBuffer(int initLength)
{
	buffer = new char[initLength];
	buffer[0] = '\0';
	//
	len = 0;
	maxlen = initLength;

}


/////////////////////////////////////////////////////////////////////////////
// destructor for the stringbuffer
/////////////////////////////////////////////////////////////////////////////
StringBuffer::~StringBuffer()
{
	delete[] buffer;
}


/////////////////////////////////////////////////////////////////////////////
// appends a character
/////////////////////////////////////////////////////////////////////////////
void StringBuffer::append(char c)
{
	if (len >= maxlen - 1)
	{
		maxlen += 1024;
		//
		char *tmp = new char[maxlen];
		strcpy(tmp, buffer);
		//
		delete[] buffer;
		buffer = tmp;
	}
	buffer[len++] = c;
	buffer[len]   = '\0';
}


/////////////////////////////////////////////////////////////////////////////
// appends a string
/////////////////////////////////////////////////////////////////////////////
void StringBuffer::append(char *str)
{
	int strLen = strlen(str);
	//
	if (len + strLen >= maxlen - 1)
	{
		maxlen += strLen + 1024;
		//
		char *tmp = new char[maxlen];
		strcpy(tmp, buffer);
		//
		delete[] buffer;
		buffer = tmp;
	}
	strcat(buffer, str);
}


/////////////////////////////////////////////////////////////////////////////
// clears the string
/////////////////////////////////////////////////////////////////////////////
void StringBuffer::clear()
{
	buffer[0] = '\0';
   len = 0;
}


/////////////////////////////////////////////////////////////////////////////
// sets the length of the string
/////////////////////////////////////////////////////////////////////////////
void StringBuffer::setLength(int len)
{
}


/////////////////////////////////////////////////////////////////////////////
// returns a char * to the buffer
/////////////////////////////////////////////////////////////////////////////
const char * StringBuffer::operator*()
{
	return buffer;
}


/////////////////////////////////////////////////////////////////////////////
// remove the last char from the stringbuffer
/////////////////////////////////////////////////////////////////////////////
void StringBuffer::operator--(int)
{
	if (len > 0)
	{
		buffer[--len] = '\0';
	}
}


