/**
 * Klasse zum Laden von '.iv' Modelldateien
 *
 * Inventor - File Format
 */
#ifndef INVENTORLDR_H
#define INVENTORLDR_H

#include "lexer.h"

class InventorLdr
{
   static char *lookup[];
   static int tokens[];

public:
   enum
   {
      INVENTOR = Lexer::USER_TOKEN,
	   SEPARATOR,
	   COORDINATE3,
   	POINT,
	   MATERIAL,
	   DIFFUSECOLOR,
   	MATERIALBINDING,
   	VALUE,
   	PER_VERTEX_INDEXED,
   	INDEXEDFACESET,
   	COORDINDEX,
   	MATERIALINDEX,
   	ASCII,
   };

   ////////////////////////////////////////////////////////////////////////////
   // static entry point for loading
   ////////////////////////////////////////////////////////////////////////////
   static bool load(char *fileName, float **coord3, int **faces, int *numCoord, int *numFaces);


   ////////////////////////////////////////////////////////////////////////////
   // read single mesh
   ////////////////////////////////////////////////////////////////////////////
   static void readSeparator(Lexer &lexer, float **coord3, int **faces, int *numCoord, int *numFaces);


   ////////////////////////////////////////////////////////////////////////////
   // read COORDINATES
   ////////////////////////////////////////////////////////////////////////////
   static void readCoordinate3(Lexer &lexer, float **coord3, int *numCoord);


   ////////////////////////////////////////////////////////////////////////////
   // read material
   ////////////////////////////////////////////////////////////////////////////
   static void readMaterial(Lexer &lexer);


   ////////////////////////////////////////////////////////////////////////////
   // read material bindings
   ////////////////////////////////////////////////////////////////////////////
   static void readMaterialBinding(Lexer &lexer);


   ////////////////////////////////////////////////////////////////////////////
   // read face set
   ////////////////////////////////////////////////////////////////////////////
   static void readIndexedFaceSet(Lexer &lexer, int **faces, int *numFaces);

};


#endif

